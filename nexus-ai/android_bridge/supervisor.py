"""Termux supervisor: restart on crash, integrity restore with a known-good snapshot.
No shell commands are generated by the LLM. Runs entirely outside Flask process.
"""
import os, sys, time, sqlite3, signal, subprocess
from pathlib import Path
from recovery import integrity, backup, restore
from nexus_stt_autoboot_r84 import start_local_stt_monitor  # NEXUS_R84_STT_AUTOBOOT

ROOT=Path(__file__).resolve().parent
HOME=Path.home()/'.nexus_ai'
DB=Path(os.environ.get('NEXUS_DB_PATH',str(HOME/'agent.sqlite3')))
SNAP=HOME/'backups'
STOP=False

def stop(signum,frame):
    global STOP
    STOP=True

def restore_corrupt_db():
    if not DB.exists() or integrity(DB):return False
    candidates=sorted(SNAP.glob('agent-*.sqlite3'),key=lambda p:p.stat().st_mtime,reverse=True)
    for shot in candidates:
        if integrity(shot):
            broken=DB.with_suffix('.corrupt-'+str(int(time.time()))+'.sqlite3')
            DB.replace(broken)  # retain failed file for forensics
            restore(DB,shot,stopped=True)
            print(f'[nexus] restored valid snapshot {shot.name}; preserved {broken.name}',flush=True)
            return True
    raise RuntimeError('Database corrupt; no valid snapshot. Refusing start.')

def run():
    signal.signal(signal.SIGINT,stop);signal.signal(signal.SIGTERM,stop)
    HOME.mkdir(parents=True,exist_ok=True)
    restore_corrupt_db()
    start_local_stt_monitor()
    failures=[]
    while not STOP:
        # Do not store an API key or privileged data in process arguments.
        child=subprocess.Popen([sys.executable,'app.py'],cwd=ROOT,env=os.environ.copy())
        print(f'[nexus] service pid={child.pid}',flush=True)
        began=time.monotonic()
        while child.poll() is None and not STOP:time.sleep(.4)
        if STOP:
            child.terminate()
            try:child.wait(timeout=6)
            except subprocess.TimeoutExpired:child.kill();child.wait()
            break
        elapsed=time.monotonic()-began
        failures=[t for t in failures if time.monotonic()-t<300]
        failures.append(time.monotonic())
        if len(failures)>=5:
            print('[nexus] crash-loop detected; refusing automatic restart',flush=True)
            break
        try:restore_corrupt_db()
        except RuntimeError as e:
            print(f'[nexus] {e}',flush=True);break
        delay=min(30,2**min(len(failures),4)) if elapsed<30 else 2
        print(f'[nexus] exited {child.returncode}; restart after {delay}s',flush=True)
        for _ in range(delay*2):
            if STOP:break
            time.sleep(.5)
    print('[nexus] supervisor stopped',flush=True)
if __name__=='__main__':run()
